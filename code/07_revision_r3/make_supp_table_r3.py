#!/usr/bin/env python3
"""make_supp_table_r3.py — supplementary tables for the third revision round.

Emits, from the cached artefacts of code/07_revision_r3/ (nothing typed by hand):

  S11  ridge penalty selected per fold, and the six primary contrasts re-tested on an
       extended penalty grid (reviewer point #10)
  S12  decodability of log genome length, including the single-window subset
       (reviewer point #3)

Usage:
    python code/07_revision_r3/make_supp_table_r3.py [--out results/tables/supplementary_tables_r3.md]
"""
import os, json, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, "..", "..")
JSON = os.path.join(REPO, "results", "json")

TARGET_LABEL = {"coding_fraction": "Coding fraction", "gene_density": "Gene density",
                "noncoding_bp": "Non-coding bp (log)", "n_genes": "Gene count (log)",
                "mean_intergenic_len": "Mean intergenic length (log)",
                "overlap_bp": "Gene overlap (log)"}
SCHEME_LABEL = {"cl95": "Identity-clustered (primary)", "family": "Family-grouped"}


def fmt_p(p):
    return "&lt; 1e-12" if p < 1e-12 else f"{p:.1e}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "results", "tables",
                                                  "supplementary_tables_r3.md"))
    a = ap.parse_args()

    al = json.load(open(os.path.join(JSON, "alpha_length_r3.json")))
    ct = json.load(open(os.path.join(JSON, "contrast_wide_grid_r3.json")))

    assert al["positive_control"]["reproduced"], "positive control of alpha_length_r3 failed"
    assert all(v["reproduced"] for v in ct["positive_control"].values()), \
        "positive control of contrast_wide_grid_r3 failed"

    L = []
    L.append("# Supplementary tables added in the third revision round\n")
    L.append("Generated by `code/07_revision_r3/make_supp_table_r3.py` from "
             "`results/json/alpha_length_r3.json` and `results/json/contrast_wide_grid_r3.json`. "
             "Both source scripts reproduce published values as a positive control before "
             "reporting: the identity-clustered R² of gene density "
             f"({al['positive_control']['obtained']:.6f}) and the published deltas of coding "
             "fraction and gene density, to six decimals.\n")

    # ---------------- S11a: penalty saturation --------------------------------
    L.append("\n## Table S11a. Ridge penalty selected inside each training fold\n")
    L.append(f"Population: the {ct['design']['population']:,} records with an assigned family; "
             f"{ct['design']['cv']['splits']} folds x {ct['design']['cv']['repeats']} repeats "
             f"(15 estimates), seed {ct['design']['cv']['seed']}. The grid declared in the manuscript is "
             "{1, 10, 100, 1000}; the extended grid spans 1e-1 to 1e6 in 15 steps. "
             "\"At grid max\" is the share of folds selecting the largest penalty of the "
             "declared grid.\n")
    L.append("| Representation | Target | Scheme | At grid max | Median penalty, extended grid |")
    L.append("|---|---|---|---|---|")
    for rep, rep_label in (("evo2_20b_blocks18", "Evo 2 20B blocks.18"), ("6mer", "6-mer")):
        for t in TARGET_LABEL:
            for s in ("cl95", "family"):
                p = ct["scores"][t]["reps"][rep][f"{s}|paper"]
                w = ct["scores"][t]["reps"][rep][f"{s}|wide"]
                L.append(f"| {rep_label} | {TARGET_LABEL[t]} | {SCHEME_LABEL[s]} | "
                         f"{100*p['frac_at_grid_max']:.0f}% | {w['alpha_median']:g} |")

    # ---------------- S11b: contrasts on both grids ---------------------------
    L.append("\n## Table S11b. The six primary contrasts on both penalty grids\n")
    L.append("Evo 2 20B blocks.18 versus the 6-mer baseline, corrected resampled t-test "
             "(Nadeau and Bengio, 2003) with Holm correction inside the set of six, as in "
             "Table S6. R² is the mean over the 15 estimates.\n")
    L.append("| Scheme | Target | R² Evo 2 (declared / extended) | R² 6-mer (declared / extended) "
             "| Delta (declared) | Delta (extended) | 95% CI (extended) | p Holm (extended) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for s in ("cl95", "family"):
        for t in TARGET_LABEL:
            pp = ct["contrasts"][f"{s}|paper"][t]
            ww = ct["contrasts"][f"{s}|wide"][t]
            L.append(f"| {SCHEME_LABEL[s]} | {TARGET_LABEL[t]} | "
                     f"{pp['r2_evo2']:.3f} / {ww['r2_evo2']:.3f} | "
                     f"{pp['r2_6mer']:.3f} / {ww['r2_6mer']:.3f} | "
                     f"{pp['delta']:+.3f} | {ww['delta']:+.3f} | "
                     f"[{ww['ci95'][0]:+.3f}, {ww['ci95'][1]:+.3f}] | {fmt_p(ww['p_holm'])} |")
    nsig = {k: sum(v["significant_holm"] for v in ct["contrasts"][k].values())
            for k in ct["contrasts"]}
    L.append(f"\nContrasts significant after Holm correction: "
             f"identity-clustered {nsig['cl95|paper']}/6 on the declared grid and "
             f"{nsig['cl95|wide']}/6 on the extended grid; family-grouped "
             f"{nsig['family|paper']}/6 and {nsig['family|wide']}/6. Direction and significance "
             "are unchanged; the magnitude of the advantage falls, because the 6-mer baseline "
             "was the more strongly affected of the two representations by the declared grid.\n")

    # ---------------- S12: genome length -------------------------------------
    d = al["design"]["population"]
    L.append("\n## Table S12. Decodability of log genome length\n")
    L.append(f"Same representation, population and folds. Of the {d['n_analysed']:,} records "
             f"analysed, {d['n_single_window']:,} ({100*d['n_single_window']/d['n_analysed']:.1f}%) "
             f"are embedded in a single {d['window_bp']:,}-bp forward pass and "
             f"{d['n_multi_window']:,} are averaged over several windows. In the single-window "
             "subset the number of pooled windows is constant at one, so a pooled-window-count "
             "artefact cannot contribute. The GC-and-length control is omitted: log length is "
             "one of its two inputs.\n")
    L.append("| Population | n | Scheme | R² (declared grid) | R² (extended grid) |")
    L.append("|---|---|---|---|---|")
    for pop, label in (("all", "All records with a family"),
                       ("single_window", f"Single window (\u2264 {d['window_bp']:,} bp)")):
        rec = al["length"][pop]
        for s in ("cl95", "family"):
            sr = rec["schemes"][s]
            L.append(f"| {label} | {rec['n']:,} | {SCHEME_LABEL[s]} | "
                     f"{sr['paper']['r2_mean']:.3f} \u00b1 {sr['paper']['r2_std']:.3f} | "
                     f"{sr['wide']['r2_mean']:.3f} |")

    dst = os.path.abspath(a.out)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"[r3] -> {dst}  ({len(L)} linhas)")


if __name__ == "__main__":
    main()
