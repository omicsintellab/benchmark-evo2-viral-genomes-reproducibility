#!/usr/bin/env python3
"""make_composition_table.py — tables for the strengthened compositional baselines (revision R1).

Reads results/json/composition_baselines_metrics.json and writes
results/tables/composition_baselines.md. No value is typed by hand.

Usage:
    python code/05_figures/make_composition_table.py
"""
import os, json
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")   # .../revisao-r1/
SRC = os.path.join(ROOT, "results", "json", "composition_baselines_metrics.json")
DST = os.path.join(ROOT, "results", "tables", "composition_baselines.md")

ORDER = ["evo2_20b_blocks18", "orf", "compo_all", "multik", "kmer6", "dicodon",
         "codon", "kmer5", "kmer4", "kmer3", "gc_len"]
SHORT = {"evo2_20b_blocks18": "Evo 2", "orf": "ORF", "compo_all": "compo_all",
         "multik": "multi-k", "kmer6": "6-mer", "dicodon": "dicodon", "codon": "codon",
         "kmer5": "5-mer", "kmer4": "4-mer", "kmer3": "3-mer", "gc_len": "GC+len"}


def fp(p):
    return "—" if p is None or not np.isfinite(p) else ("<1e-4" if p < 1e-4 else f"{p:.2g}")


def main():
    d = json.load(open(SRC))
    dims, L = d["config"]["dims"], []

    L.append("# Strengthened compositional baselines (revision R1, stage 3)\n")
    L.append(f"Generated by `code/05_figures/make_composition_table.py`. "
             f"Population: **{d['population']['n']:,}** genomes with an assigned family, "
             f"{d['population']['n_families']} families. Ridge probes, "
             f"{d['config']['splits']}-fold x {d['config']['repeats']} repeats.\n")
    L.append("Answers R1 3.4 (\"a 6-mer table is only one way to describe composition\") and "
             "R2 #3 (\"ORF count, longest ORF, ORF coverage, stop-codon density and six-frame "
             "coding potential should be included\").\n")
    L.append("Representations (dimensionality): " +
             ", ".join(f"`{SHORT.get(k,k)}`={dims[k]}" for k in ORDER if k in dims) + ".\n")
    L.append(f"ORF feature set: {', '.join('`'+c+'`' for c in d['config']['orf_features'])}.\n")
    L.append(f"> Coverage note: {d['config']['coverage_note']}\n")

    for scheme, title in (("cl95", "A. Pre-registered scheme (95% identity clusters)"),
                          ("family", "B. Family-grouped CV")):
        L.append(f"\n## Table R1-{'G' if scheme=='cl95' else 'H'}. {title}\n")
        L.append("R² per representation. Best baseline per row in bold.\n")
        L.append("| Target | " + " | ".join(SHORT.get(r, r) for r in ORDER) + " |")
        L.append("|---" * (len(ORDER) + 1) + "|")
        for t, v in d["targets"].items():
            vals = {r: v["reps"][r][scheme]["mean"] for r in ORDER}
            best = max((r for r in ORDER if r != "evo2_20b_blocks18"), key=lambda r: vals[r])
            cells = []
            for r in ORDER:
                s = f"{vals[r]:.3f}"
                cells.append(f"**{s}**" if r == best else s)
            tag = "" if v["primary"] else " *(neg. ctrl)*"
            L.append(f"| {t}{tag} | " + " | ".join(cells) + " |")

    CLS_TITLE = {"compositional": "compositional baselines (k-mer, codon, dicodon, GC+length)",
                 "annotation_like": "annotation-like baselines (6-frame ORF scan)"}
    L.append("\n## Evo 2 vs the best baseline, **by baseline class**\n")
    L.append(d.get("classes_note", "") + "\n")
    for cls, members in d["classes"].items():
        L.append(f"\n### {CLS_TITLE.get(cls, cls)}\n")
        L.append("Members: " + ", ".join(f"`{SHORT.get(m, m)}`" for m in members) + "\n")
        L.append("| Scheme | Target | Evo 2 | Best in class | ΔR² | 95% CI | p | Evo 2 ahead? |")
        L.append("|---|---|---|---|---|---|---|---|")
        for scheme in ("cl95", "family"):
            for t, v in d["tests"][scheme].items():
                c = v["by_class"][cls]
                L.append(f"| {scheme} | {t} | {v['evo2_r2']:.3f} | "
                         f"{SHORT.get(c['best'], c['best'])} ({c['best_r2']:.3f}) | "
                         f"{c['delta']:+.3f} | [{c['ci95'][0]:.3f}, {c['ci95'][1]:.3f}] | "
                         f"{fp(c['p'])} | {'yes' if c['evo2_ahead'] else '**no**'} |")

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    open(DST, "w").write("\n".join(L) + "\n")
    print(f"[ok] -> {DST}")


if __name__ == "__main__":
    main()
