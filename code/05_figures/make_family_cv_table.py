#!/usr/bin/env python3
"""make_family_cv_table.py — tabelas do CV agrupado por família (revisão R1).

Lê results/json/family_cv_metrics.json (produzido por code/03_analysis/family_cv.py)
e escreve results/tables/family_cv.md. Nenhum valor é digitado à mão.

Uso: python code/05_figures/make_family_cv_table.py
"""
import os, json, numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, "..", "..")
SRC = os.path.join(REPO, "results", "json", "family_cv_metrics.json")
DST = os.path.join(REPO, "results", "tables", "family_cv.md")
SPLITS = 5


def nadeau_bengio(a, b, k=SPLITS):
    d = np.asarray(a) - np.asarray(b); n = len(d); v = d.var(ddof=1)
    if n < 2 or v == 0: return float("nan"), float("nan")
    t = d.mean() / np.sqrt((1 / n + 1 / (k - 1)) * v)
    return float(t), float(2 * stats.t.sf(abs(t), n - 1))


def fp(p):
    return "—" if not np.isfinite(p) else ("<1e-4" if p < 1e-4 else f"{p:.2g}")


def main():
    d = json.load(open(SRC))
    pop, cfg = d["population"], d["config"]
    prim = [k for k, v in d["targets"].items() if v["primary"]]
    neg = [k for k, v in d["targets"].items() if not v["primary"]]
    L = []

    L.append("# Cross-validation grouped by viral family (revision R1)\n")
    L.append(f"Generated by `code/05_figures/make_family_cv_table.py` from "
             f"`results/json/family_cv_metrics.json`. Population: **{pop['n_analysed']:,}** genomes "
             f"with an assigned family, out of {pop['n_with_embedding']:,} with a cached embedding "
             f"({pop['n_without_family']} dropped for lacking a family). "
             f"{pop['n_families']} families; {pop['n_multirecord_organisms']} multi-record organisms "
             f"(segmented/multipartite) are kept in the same fold by construction, since family "
             f"grouping subsumes organism grouping.\n")
    L.append(f"Ridge probes, {cfg['splits']}-fold x {cfg['repeats']} repeats, alphas {cfg['alphas']}, "
             f"seed {cfg['seed']}. LOFO = leave-one-family-out over the "
             f"{len(cfg['lofo_families'])} families with n >= {cfg['min_lofo']}.\n")

    # --- T1: R2 por esquema
    L.append("\n## Table R1-A. R² by cross-validation scheme\n")
    L.append("`random` and `cl95` are the schemes reported in the submitted manuscript; "
             "`family` and `LOFO` are new. LOFO reports the pooled out-of-fold R².\n")
    L.append("| Target | Representation | random | cl95 | family | LOFO (pooled) |")
    L.append("|---|---|---|---|---|---|")
    for t in prim + neg:
        for r in ["evo2_20b_blocks18", "6mer", "gc_len"]:
            x = d["targets"][t]["reps"][r]
            L.append(f"| {t} | {r} | {x['random']['mean']:.3f} | {x['cl95']['mean']:.3f} | "
                     f"**{x['family']['mean']:.3f}** | {x['lofo']['pooled_r2']:.3f} |")

    # --- T2: testes primarios
    L.append("\n## Table R1-B. Primary confirmatory tests — Evo 2 vs 6-mer, family-grouped CV\n")
    L.append("Six pre-specified contrasts, corrected resampled t-test (Nadeau & Bengio) with "
             "Holm correction within the family of six. ΔR² = Evo 2 − 6-mer; CI is a 10,000-draw "
             "bootstrap over the fold deltas.\n")
    L.append("| Target | Evo 2 | 6-mer | ΔR² | 95% CI | t | p | p (Holm) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for t in prim:
        v = d["primary_tests"]["tests"][t]
        e = d["targets"][t]["reps"]["evo2_20b_blocks18"]["family"]["mean"]
        k = d["targets"][t]["reps"]["6mer"]["family"]["mean"]
        L.append(f"| {t} | {e:.3f} | {k:.3f} | {v['delta_mean']:.3f} | "
                 f"[{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}] | {v['t_nadeau_bengio']:.2f} | "
                 f"{fp(v['p_raw'])} | {fp(v['p_holm'])} |")

    # --- T3: contraste contra GC+len (exploratorio)
    L.append("\n## Table R1-C. Exploratory — Evo 2 vs GC+length, family-grouped CV\n")
    L.append("Not part of the confirmatory set and **not** corrected for multiplicity. Reported "
             "because GC+length is the other baseline in the manuscript and is a far stronger "
             "competitor than the 6-mer on the length-linked targets.\n")
    L.append("| Target | Evo 2 | GC+len | ΔR² | t | p (uncorrected) |")
    L.append("|---|---|---|---|---|---|")
    for t in prim:
        e = d["targets"][t]["reps"]["evo2_20b_blocks18"]["family"]["scores"]
        g = d["targets"][t]["reps"]["gc_len"]["family"]["scores"]
        tt, p = nadeau_bengio(e, g)
        L.append(f"| {t} | {np.mean(e):.3f} | {np.mean(g):.3f} | {np.mean(e) - np.mean(g):.3f} | "
                 f"{tt:.2f} | {fp(p)} |")

    # --- T4: LOFO por familia
    L.append("\n## Table R1-D. Leave-one-family-out, Evo 2 — pooled vs per-family\n")
    L.append("The pooled R² is computed over the stacked out-of-fold predictions; the per-family "
             "R² is computed **within** each held-out family. A pooled R² well above the per-family "
             "values means the probe is tracking between-family differences (i.e. family identity) "
             "rather than within-family architecture — the confound both reviewers raised.\n")
    L.append("| Target | Pooled R² | Median per-family R² | Families with R² < 0 |")
    L.append("|---|---|---|---|")
    for t in prim:
        l = d["targets"][t]["reps"]["evo2_20b_blocks18"]["lofo"]
        pf = list(l["per_family"].values())
        nneg = sum(1 for x in pf if x < 0)
        L.append(f"| {t} | {l['pooled_r2']:.3f} | {np.median(pf):.3f} | {nneg}/{len(pf)} |")

    # --- T5: controle negativo
    L.append("\n## Table R1-E. Pre-declared negative control (dinucleotide composition)\n")
    L.append("`cpg_oe` and `upa_oe` are composition targets, declared in advance as cases where the "
             "6-mer baseline is **expected** to win. Outside the multiplicity correction; they are a "
             "specificity check on the probe, not hypothesis tests.\n")
    L.append("| Target | Evo 2 | 6-mer | ΔR² | 95% CI | p (uncorrected) |")
    L.append("|---|---|---|---|---|---|")
    for t in neg:
        v = d["negative_control"]["tests"][t]
        e = d["targets"][t]["reps"]["evo2_20b_blocks18"]["family"]["mean"]
        k = d["targets"][t]["reps"]["6mer"]["family"]["mean"]
        L.append(f"| {t} | {e:.3f} | {k:.3f} | {v['delta_mean']:.3f} | "
                 f"[{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}] | {fp(v['p_raw'])} |")

    # --- T6: CV dentro de família (se disponível)
    WF = os.path.join(REPO, "results", "json", "within_family_cv_metrics.json")
    if os.path.exists(WF):
        w = json.load(open(WF))
        L.append("\n## Table R1-F. Within-family cross-validation\n")
        L.append("Trained and tested **inside** the same family, for families with "
                 f"n >= {w['config']['min_n']}. This isolates within-family signal from the "
                 "transfer problem that LOFO confounds it with. `SD ratio` is the median "
                 "within-family SD of the target over its global SD: where it is small, a low R² "
                 "is expected from restriction of range alone, regardless of the model. "
                 "Wilcoxon signed-rank is paired across families and is exploratory.\n")
        L.append("| Target | Families | SD ratio (median) | Evo 2 | 6-mer | GC+len | Evo 2 R²>0 | p vs 6-mer | p vs GC+len |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for t, v in w["targets"].items():
            s = v["summary"]; m = s["median_r2"]
            ratio = np.median([f["sd_ratio"] for f in v["families"].values()])
            p1 = s.get("wilcoxon_evo2_vs_6mer", {}).get("p", float("nan"))
            p2 = s.get("wilcoxon_evo2_vs_gclen", {}).get("p", float("nan"))
            L.append(f"| {t} | {s['n_families']} | {ratio:.2f} | {m['evo2_20b_blocks18']:.3f} | "
                     f"{m['6mer']:.3f} | {m['gc_len']:.3f} | "
                     f"{s['n_families_evo2_positive']}/{s['n_families']} | {fp(p1)} | {fp(p2)} |")

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"[ok] -> {DST}")


if __name__ == "__main__":
    main()
