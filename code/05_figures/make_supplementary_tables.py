#!/usr/bin/env python3
"""make_supplementary_tables.py — Supplementary Tables S1-S4 from the cached metrics.

Every number in the Supplementary Material of the paper is regenerated here from the
JSONs in results/json/ and the corpus manifest in data/ — nothing is typed by hand.
Runs on CPU in a second; no GPU and no cached embeddings required.

  S1  Precision control on the H100: native FP8 vs forced bfloat16 (Section 2.5).
  S2  Random vs sequence-identity cluster-aware cross-validation (Section 3.1).
  S3  Dimensionality-matched comparison, 150-component PCA fit within folds (Section 3.4).
  S4  Corpus composition: Baltimore class x host domain (Section 2.1).

Usage:
    python code/05_figures/make_supplementary_tables.py

Output: results/tables/supplementary_tables.md
"""
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, "..", "..")
JSON = os.path.join(REPO, "results", "json")
DATA = os.path.join(REPO, "data")
OUT = os.path.join(REPO, "results", "tables", "supplementary_tables.md")

# Probe targets shared by S1-S3, in the order used in the paper.
LABEL = {
    "Baltimore": "Baltimore class (acc)",
    "Host": "Host domain (acc)",
    "Family": "Family (acc)",
    "coding_fraction": "coding_fraction (R²)",
    "gene_density": "gene_density (R²)",
    "noncoding_bp": "noncoding_bp, log (R²)",
    "n_genes": "n_genes, log (R²)",
    "mean_intergenic_len": "mean_intergenic_len, log (R²)",
}
TARGETS = list(LABEL)

load = lambda name: json.load(open(os.path.join(JSON, name)))
fmt = lambda d: f"{d['mean']:.3f} ± {d['std']:.3f}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main():
    scale = load("scale_metrics.json")["results"]
    prec = load("precision_control_metrics.json")["reps"]
    pca = load("pca_control_metrics.json")
    doc = ["# Supplementary Tables",
           "",
           "Generated by `code/05_figures/make_supplementary_tables.py` from the cached metrics "
           "in `results/json/` and the corpus manifest in `data/`. Classification reports accuracy; "
           "regression reports R². Values are mean ± SD over repeated cross-validation.",
           ""]

    # ---- S1: precision control -------------------------------------------------
    doc += ["## Table S1. Precision control on the NVIDIA H100 (native FP8 vs forced bfloat16)",
            "",
            "Cluster-aware cross-validation, identical genomes and folds. Forcing bfloat16 degrades "
            "every target, most severely the fine-grained architectural features — the 20B checkpoint "
            "is calibrated for FP8 inference rather than precision-agnostic.",
            ""]
    doc += [md_table(
        ["Probe target", "blocks.15 FP8", "blocks.15 bfloat16", "blocks.18 FP8", "blocks.18 bfloat16"],
        [[LABEL[t]] + [fmt(prec[f"blocks{layer}_{p}"][t]["clus"])
                       for layer in (15, 18) for p in ("fp8", "bf16")]
         for t in TARGETS])]
    doc += [""]

    # ---- S2: random vs cluster-aware CV ---------------------------------------
    rows, deltas = [], []
    for t in TARGETS:
        a, b = scale["20B_blocks18"][t], scale["7B_blocks28"][t]
        d20 = a["clus"]["mean"] - a["rand"]["mean"]
        d7 = b["clus"]["mean"] - b["rand"]["mean"]
        deltas += [abs(d20), abs(d7)]
        rows.append([LABEL[t], fmt(a["rand"]), fmt(a["clus"]), f"{d20:+.3f}",
                     fmt(b["rand"]), fmt(b["clus"]), f"{d7:+.3f}"])
    doc += ["## Table S2. Random vs sequence-identity cluster-aware cross-validation",
            "",
            "Groups are MMseqs2 linclust clusters (95% identity, 85% coverage), so no cluster spans "
            "training and held-out folds. Δ is the change induced by the group-aware scheme.",
            ""]
    doc += [md_table(["Probe target", "20B random CV", "20B cluster-aware CV", "Δ",
                      "7B random CV", "7B cluster-aware CV", "Δ"], rows)]
    doc += ["",
            f"*Largest absolute change across all targets and both models: {max(deltas):.3f} — "
            f"well within the fold-to-fold standard deviation, confirming that the reported scores "
            f"are not inflated by near-duplicate leakage.*",
            ""]

    # ---- S3: dimensionality-matched PCA ---------------------------------------
    rp = pca["reps"]
    doc += [f"## Table S3. Dimensionality-matched comparison ({pca['pca_dim']}-component PCA, fit within each fold)",
            "",
            "The 20B embedding is higher-dimensional than the 7B (8,192 vs 4,096 components), which "
            "could by itself inflate linear-probe scores. Projecting both onto a common low-dimensional "
            "subspace preserves the 20B advantage — the effect is of model scale, not embedding width.",
            ""]
    doc += [md_table(["Probe target", "20B full (8,192-d)", "20B PCA-150", "7B full (4,096-d)", "7B PCA-150"],
                     [[LABEL[t], fmt(scale["20B_blocks18"][t]["clus"]), fmt(rp["20B_blocks18"][t]["clus_pca"]),
                       fmt(scale["7B_blocks28"][t]["clus"]), fmt(rp["7B_blocks28"][t]["clus_pca"])]
                      for t in TARGETS])]
    doc += [""]

    # ---- S4: corpus composition ------------------------------------------------
    man = pd.read_csv(os.path.join(DATA, "corpus_manifest.tsv.gz"), sep="\t")
    ct = pd.crosstab(man.baltimore, man.host)
    order = [c for c in ["eukaryote", "bacteria", "archaea"] if c in ct.columns]
    order += [c for c in ct.columns if c not in order]
    names = {"I": "I (dsDNA)", "II": "II (ssDNA)", "III": "III (dsRNA)", "IV": "IV (ssRNA+)",
             "V": "V (ssRNA−)", "VI": "VI (ssRNA-RT)", "VII": "VII (dsDNA-RT)", "?": "Unassigned"}
    rows = []
    for b in ["I", "II", "III", "IV", "V", "VI", "VII", "?"]:
        if b not in ct.index:
            continue
        r = ct.loc[b]
        rows.append([names[b]] + [f"{int(r[c]):,}" for c in order] + [f"{int(r.sum()):,}"])
    tot = ct.sum()
    rows.append(["**Total**"] + [f"**{int(tot[c]):,}**" for c in order] + [f"**{int(tot.sum()):,}**"])
    doc += [f"## Table S4. Corpus composition: Baltimore class × host domain (n = {len(man):,} records)",
            "",
            "Records include individual segments of segmented viruses. Entries whose family- or "
            "genus-level taxonomy could not be mapped to the ICTV VMR (MSL41) are reported as "
            "unassigned/unknown; probe subsets were drawn as balanced samples from the quota groups, "
            "so the imbalance of the full corpus does not propagate into the probes.",
            ""]
    doc += [md_table(["Baltimore class"] + [c.title() for c in order] + ["Total"], rows)]
    doc += [""]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(doc))
    print(f"[ok] {OUT}")


if __name__ == "__main__":
    main()
